"""
control/safety_supervisor.py - Centralized Safety Supervisor for Autonomous RC Car.

Authority & Role:
The SafetySupervisor has final override authority over all motion commands
generated by navigation planners, remote clients, or AI models.

Safety Rules Enforced:
1. Proximity Failsafe: Immediate STOP if valid obstacle <= emergency_stop_distance_cm.
2. Sensor Freshness Failsafe: Immediate STOP if enabled ultrasonic data is older than max_stale_sensor_sec.
3. Vision Freshness Failsafe: Immediate STOP if camera frame is older than max_camera_age_sec or camera is blind.
4. Command Validation: Rejects NaN, Inf, or invalid/unsupported actions.
5. Speed Clamping: Clamps throttle strictly within [0.0, max_speed_limit] for safety and electrical protection.
6. Reversal Deadband: Prevents instantaneous flip between forward and reverse motion to eliminate L298N inductive spikes and Pi 4 voltage sag.
7. Software Watchdog: Auto-stops motors if the control loop misses its deadline.
8. Emergency Stop: Latched hardware halt callable from dashboard, sensors, or operator.
"""

import os
import sys
import time
import math
import logging
from dataclasses import dataclass, field
from typing import Optional, Dict, Any, List, Tuple

curr_dir = os.path.dirname(os.path.abspath(__file__)) if "__file__" in locals() else "."
parent_dir = os.path.dirname(curr_dir)
if parent_dir not in sys.path:
    sys.path.insert(0, parent_dir)

try:
    from config import SafetyConfig
    from sensors.ultrasonic import SingleSensorData, DualUltrasonicData
except ImportError:
    from autonomous_car.config import SafetyConfig
    from autonomous_car.sensors.ultrasonic import SingleSensorData, DualUltrasonicData

logger = logging.getLogger(__name__)


@dataclass
class MotionCommand:
    throttle: float = 0.0     # -1.0 (rev) to +1.0 (fwd)
    steering: float = 0.0     # -1.0 (left) to +1.0 (right)
    action: str = "STOP"      # STOP, FORWARD, TURN_LEFT, TURN_RIGHT, REVERSE
    source: str = "planner"
    timestamp: float = field(default_factory=time.time)


@dataclass
class SafeCommandResult:
    allowed: bool
    safe_throttle: float
    safe_steering: float
    action: str
    reason: str
    is_emergency_stop: bool = False
    timestamp: float = field(default_factory=time.time)


class SafetySupervisor:
    """
    Central safety arbiter enforcing deterministic vehicle safety limits.
    """

    def __init__(self, config: Optional[SafetyConfig] = None) -> None:
        self.config: SafetyConfig = config or SafetyConfig()
        self._emergency_stop_latched: bool = False
        self._emergency_stop_reason: str = ""
        self._last_heartbeat: float = time.monotonic()
        self._last_throttle_sign: int = 0  # +1 = fwd, -1 = rev, 0 = stop
        self._last_direction_change_time: float = time.monotonic()
        self._reversal_hold_until: float = 0.0
        self.stop_events: List[Dict[str, Any]] = []

    def heartbeat(self) -> None:
        """Call each control loop iteration to reset the safety watchdog."""
        self._last_heartbeat = time.monotonic()

    def emergency_stop(self, reason: str = "Operator Emergency Stop") -> SafeCommandResult:
        """Latches an immediate emergency stop."""
        self._emergency_stop_latched = True
        self._emergency_stop_reason = reason
        self._log_stop_event("EMERGENCY_STOP", reason)
        return SafeCommandResult(
            allowed=False,
            safe_throttle=0.0,
            safe_steering=0.0,
            action="STOP",
            reason=f"EMERGENCY STOP LATCHED: {reason}",
            is_emergency_stop=True,
        )

    def reset_emergency_stop(self) -> None:
        """Clears latched emergency stop."""
        self._emergency_stop_latched = False
        self._emergency_stop_reason = ""
        self._last_heartbeat = time.monotonic()
        logger.info("[SAFETY SUPERVISOR] Emergency stop reset. Vehicle back in standby.")

    @property
    def is_emergency_stopped(self) -> bool:
        return self._emergency_stop_latched

    def validate_command(
        self,
        proposed: MotionCommand,
        ultrasonic: Optional[SingleSensorData] = None,
        camera_frame_age_sec: Optional[float] = None,
        is_blind: bool = False,
        now: Optional[float] = None,
    ) -> SafeCommandResult:
        """
        Validates proposed motion command against all safety gates.
        Returns a SafeCommandResult with clamped, safe motor values or a safety STOP.
        """
        cur_time = now if now is not None else time.time()
        mono_now = time.monotonic()

        # Gate 0: Latched Emergency Stop
        if self._emergency_stop_latched:
            return SafeCommandResult(
                allowed=False,
                safe_throttle=0.0,
                safe_steering=0.0,
                action="STOP",
                reason=f"Emergency stop active ({self._emergency_stop_reason})",
                is_emergency_stop=True,
            )

        # Gate 1: Watchdog Deadline Check
        loop_elapsed = mono_now - self._last_heartbeat
        watchdog_limit = getattr(self.config, 'watchdog_timeout_sec', 0.6)
        if loop_elapsed > watchdog_limit:
            reason = f"Main control loop watchdog expired ({loop_elapsed:.2f}s > {watchdog_limit:.2f}s)"
            self._log_stop_event("WATCHDOG_TIMEOUT", reason)
            return SafeCommandResult(
                allowed=False,
                safe_throttle=0.0,
                safe_steering=0.0,
                action="STOP",
                reason=reason,
                is_emergency_stop=True,
            )

        # Gate 2: Input Sanity & Validity
        if math.isnan(proposed.throttle) or math.isinf(proposed.throttle) or \
           math.isnan(proposed.steering) or math.isinf(proposed.steering):
            reason = f"Rejected invalid command values: throttle={proposed.throttle}, steering={proposed.steering}"
            self._log_stop_event("INVALID_COMMAND", reason)
            return SafeCommandResult(
                allowed=False,
                safe_throttle=0.0,
                safe_steering=0.0,
                action="STOP",
                reason=reason,
            )

        # Gate 3: Camera & Vision Freshness Check
        if camera_frame_age_sec is not None:
            max_cam_age = getattr(self.config, 'max_camera_age_sec', 0.8)
            if camera_frame_age_sec > max_cam_age:
                reason = f"Camera feed stale ({camera_frame_age_sec:.2f}s > {max_cam_age:.2f}s)"
                self._log_stop_event("STALE_CAMERA", reason)
                return SafeCommandResult(
                    allowed=False,
                    safe_throttle=0.0,
                    safe_steering=0.0,
                    action="STOP",
                    reason=reason,
                )

        if is_blind:
            reason = "Camera is blind (scene dark or image flat)"
            self._log_stop_event("VISION_BLIND", reason)
            return SafeCommandResult(
                allowed=False,
                safe_throttle=0.0,
                safe_steering=0.0,
                action="STOP",
                reason=reason,
            )

        # Gate 4: Ultrasonic Sensor Checks (if enabled)
        if ultrasonic is not None:
            # Check sensor staleness
            if ultrasonic.timestamp > 0:
                sensor_age = cur_time - ultrasonic.timestamp
                max_stale = getattr(self.config, 'max_stale_sensor_sec', 0.5)
                if sensor_age > max_stale:
                    reason = f"Ultrasonic sensor data stale ({sensor_age:.2f}s > {max_stale:.2f}s)"
                    self._log_stop_event("STALE_SENSOR", reason)
                    return SafeCommandResult(
                        allowed=False,
                        safe_throttle=0.0,
                        safe_steering=0.0,
                        action="STOP",
                        reason=reason,
                    )

            # A configured ultrasonic sensor that has no valid sample is a
            # sensor fault, not evidence of a clear path. Never permit motion
            # while the obstacle sensor is reporting TIMEOUT/FAULT data.
            if not ultrasonic.is_valid and abs(proposed.throttle) > 0.05:
                reason = f"Ultrasonic sensor invalid ({ultrasonic.status}); motion prohibited until a valid sample arrives."
                self._log_stop_event("INVALID_SENSOR", reason)
                return SafeCommandResult(
                    allowed=False,
                    safe_throttle=0.0,
                    safe_steering=0.0,
                    action="STOP",
                    reason=reason,
                )

            # Check close-range obstacle stop distance
            if ultrasonic.is_valid and ultrasonic.distance_cm is not None:
                stop_dist = getattr(self.config, 'emergency_stop_distance_cm', 20.0)
                if ultrasonic.distance_cm <= stop_dist and proposed.throttle > 0.0:
                    reason = f"Obstacle detected at {ultrasonic.distance_cm:.1f}cm <= {stop_dist:.1f}cm limit. Forward motion prohibited."
                    self._log_stop_event("PROXIMITY_STOP", reason)
                    return SafeCommandResult(
                        allowed=False,
                        safe_throttle=0.0,
                        safe_steering=0.0,
                        action="STOP",
                        reason=reason,
                    )

        # Gate 5: Speed Clamping (Electrical & Thermal Protection)
        max_limit = getattr(self.config, 'max_speed_limit', 0.70)
        clamped_throttle = max(-max_limit, min(max_limit, proposed.throttle))
        clamped_steering = max(-1.0, min(1.0, proposed.steering))

        # Gate 6: Reversal Deadband Protection
        current_sign = 1 if clamped_throttle > 0.05 else (-1 if clamped_throttle < -0.05 else 0)
        reversal_deadband = getattr(self.config, 'reversal_deadband_sec', 0.08)

        if mono_now < self._reversal_hold_until and current_sign != 0:
            return SafeCommandResult(
                allowed=True,
                safe_throttle=0.0,
                safe_steering=clamped_steering,
                action="STOP",
                reason="Reversal deadband damping (L298N back-EMF protection)",
            )

        if self._last_throttle_sign != 0 and current_sign != 0 and current_sign != self._last_throttle_sign:
            # Direct forward<->reverse flip: hold neutral for the deadband to
            # quench H-bridge inductive kickback, then allow the new direction.
            self._reversal_hold_until = mono_now + reversal_deadband
            self._last_throttle_sign = 0
            self._last_direction_change_time = mono_now
            return SafeCommandResult(
                allowed=True,
                safe_throttle=0.0,
                safe_steering=clamped_steering,
                action="STOP",
                reason="Reversal deadband damping (L298N back-EMF protection)",
            )

        if current_sign != self._last_throttle_sign:
            self._last_direction_change_time = mono_now
            self._last_throttle_sign = current_sign

        action = proposed.action
        if abs(clamped_throttle) < 0.05 and abs(clamped_steering) < 0.05:
            action = "STOP"
        elif clamped_throttle > 0 and abs(clamped_steering) < 0.15:
            action = "FORWARD"
        elif clamped_throttle < 0:
            action = "REVERSE"
        elif clamped_steering < -0.15:
            action = "TURN_LEFT"
        elif clamped_steering > 0.15:
            action = "TURN_RIGHT"

        return SafeCommandResult(
            allowed=True,
            safe_throttle=clamped_throttle,
            safe_steering=clamped_steering,
            action=action,
            reason="Command validated safely by supervisor",
        )

    def _log_stop_event(self, event_type: str, reason: str) -> None:
        event = {
            "timestamp": time.time(),
            "type": event_type,
            "reason": reason,
        }
        self.stop_events.append(event)
        if len(self.stop_events) > 100:
            self.stop_events.pop(0)
        logger.warning(f"[SAFETY STOP - {event_type}] {reason}")
